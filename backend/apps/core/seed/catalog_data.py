CREAMY = "#FBF5E8"


def P(
    sku,
    name,
    cat,
    price,
    short,
    desc,
    *,
    art,
    tint=None,
    type="BEVERAGE",
    groups=(),
    flags="",
    mode="PREPARED",
    prep=5,
    cal=None,
    caf=None,
    allergens=(),
    tags=(),
    active=True,
    sold_out=False,
    sort=0,
    nutrition=None,
):
    return dict(
        sku=sku,
        name=name,
        cat=cat,
        price=D(price),
        short=short,
        desc=desc,
        art=art,
        tint=tint,
        type=type,
        groups=list(groups),
        flags=flags,
        mode=mode,
        prep=prep,
        cal=cal,
        caf=caf,
        allergens=list(allergens),
        tags=list(tags),
        active=active,
        sold_out=sold_out,
        sort=sort,
        nutrition=nutrition or {},
    )


def cup(shape="cup", glaze="cream", surface="rosetta", base=LATTE_BASE, accent=CREAMY, **kw):
    return ("cup", dict(shape=shape, glaze=glaze, surface=surface, base=base, accent=accent, **kw))


def glass(**kw):
    return ("glass", kw)


def food(item, **kw):
    return ("food", dict(item=item, **kw))


def bag(color, origin, sub, notes, roast):
    return ("bag", dict(color=color, origin=origin, sub=sub, notes=notes, roast=roast))


def gear(item, **kw):
    return ("gear", dict(item=item, **kw))


